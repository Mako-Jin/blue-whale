-- V6 · 客户端技术日志增加租户维度（H2 方言）
--
-- 与 db/migration/mysql/V6__*.sql、db/migration/dameng/V6__*.sql 结构一一对应，
-- 差别只在方言（见文件末尾）。
--
-- 【为什么是 V6】Flyway 的 locations 是全模块共享的 classpath:db/migration/<vendor>，
-- 版本号**全仓唯一**：V1 日志域、V2 行为事件域、V3/V5 权限域、V4 审计域，本片接 V6。
-- 详见 docs/decisions/0009。
--
-- 【本次一件事】bw_client_log 增加 tenant_id。
--
-- 【为什么必须可空（NULL）】
--   日志的**上报接口是公开的**（登录页出错时也要能上报，见 ClientLogController）。
--   未登录时服务端拿不到身份，自然也拿不到租户 —— 那一批日志的 tenant_id 只能是 NULL。
--   写成 NOT NULL 会让"登录前上报"直接失败，而登录页的错误恰恰是最需要诊断的一批。
--
-- 【NULL 的语义：不属于任何租户，因此对任何租户都不可见】
--   查询侧一律强制 tenant_id = 当前登录租户，NULL 不匹配任何值，这些记录**查不出来**。
--   这是刻意的取舍，不是遗漏：无法判断一条匿名日志属于哪个租户，
--   把它展示给"当前租户"就等于把别的租户的匿名日志一并展示出去 ——
--   而登录页日志里可能带着用户输入的用户名。宁可不显示，不可错显示。
--   代价与后续选项见 docs/decisions/0026。
--
-- 【历史数据不回填 —— 升级时请留意】
--   本脚本**不 UPDATE 任何现有行**，因此升级后已有日志的 tenant_id 全是 NULL，
--   即"升级前的日志一条也查不出来"。这不是 bug：库里从来没有记录过归属，
--   任何回填值都是编造的，而编造出来的归属比查不到更危险。
--   日志本身是短保留期数据（默认时间窗 7 天），升级后自然过期即可。
--   若某个部署确实需要保留，那是**部署决策**（把历史行归给哪个租户），
--   应在环境侧用一次性脚本完成，不要写进本仓的版本迁移 ——
--   一旦写进来，所有环境的"未知归属"都会被同一句 UPDATE 变成同一个租户的数据。
-- ============================================================================

ALTER TABLE bw_client_log
    ADD COLUMN tenant_id BIGINT DEFAULT NULL;

-- 索引跟着查询形状走：查询恒定带租户，且几乎恒定带时间窗，
-- 因此 (tenant_id, server_time DESC) 是本表升级后最常用的入口。
-- 不为 tenant_id 单建索引：单列索引在最常见的"租户 + 时间窗"查询里
-- 会先按租户取出全部行再逐行比时间，反而比联合索引更慢。
CREATE INDEX idx_bw_client_log_tenant_time ON bw_client_log (tenant_id, server_time DESC);

