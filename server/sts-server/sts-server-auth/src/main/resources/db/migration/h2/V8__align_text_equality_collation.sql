-- 【本 profile 的 H2 原生替代品，以及为什么没用它】
-- H2 有 `VARCHAR_IGNORECASE` 类型（实测有效），但它做的是**反方向**的事
-- —— 那是"大小写不敏感"。本片要的是"敏感"，也就是 H2 的默认值。
